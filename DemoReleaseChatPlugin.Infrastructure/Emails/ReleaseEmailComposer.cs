using DemoReleaseChatPlugin.Application.Releases.Emails;
using DemoReleaseChatPlugin.Application.Releases.Emails.Messages;
using DoverPort.Emails;

namespace DemoReleaseChatPlugin.Infrastructure.Emails;

/// <summary>
/// Every user-supplied value goes through <see cref="Encode"/>. Project names, versions, notes and
/// reasons are free text typed by a person; the subject line and the &lt;strong&gt; labels are the
/// only literals.
///
/// Subject prefixes [Scheduled release] / [Released] / [Rolled back] exist so recipients can filter
/// in their mail client.
/// </summary>
public class ReleaseEmailComposer : IReleaseEmailComposer
{
    private const string Signature = "This message was auto-generated by";
    private const string SignatureApp = "DemoReleaseChatPlugin Release Management";

    public (string Subject, string BodyHtml) Compose(ScheduledReleaseAnnouncement announcement)
    {
        var subject = $"[Scheduled release] {announcement.ProjectName} {announcement.Version} - {Format(announcement.ScheduledFor)}";

        var builder = new PodEmailBuilder()
            .AppendTitle($"Scheduled production release: {announcement.ProjectName} {announcement.Version}")
            .AppendParagraph($"A production release has been scheduled for <strong>{Format(announcement.ScheduledFor)}</strong>.")
            .AppendParagraph($"<strong>Project:</strong> {Encode(announcement.ProjectName)}")
            .AppendParagraph($"<strong>Version:</strong> {Encode(announcement.Version)}")
            .AppendParagraph($"<strong>Lead developer:</strong> {Encode(announcement.LeadDeveloper)}");

        if (announcement.RiskLevel is not null)
        {
            builder.AppendParagraph(string.IsNullOrWhiteSpace(announcement.RiskNotes)
                ? $"<strong>Risk / impact:</strong> {announcement.RiskLevel}"
                : $"<strong>Risk / impact ({announcement.RiskLevel}):</strong><br/>{ToHtml(announcement.RiskNotes)}");
        }

        if (!string.IsNullOrWhiteSpace(announcement.Summary))
            builder.AppendParagraph($"<strong>Summary of changes:</strong><br/>{ToHtml(announcement.Summary)}");

        builder.AppendParagraph(
            "This is an advance notice so the deployment window can be planned around. No action is required.");

        return (subject, builder.AppendSignature(Signature, SignatureApp).GenerateContent());
    }

    public (string Subject, string BodyHtml) Compose(LiveReleaseAnnouncement announcement)
    {
        var subject = $"[Released] {announcement.ProjectName} {announcement.Version} is live - {Format(announcement.DeployedOn)}";

        var builder = new PodEmailBuilder()
            .AppendTitle($"{announcement.ProjectName} {announcement.Version} has been released to production")
            .AppendParagraph($"Deployed at <strong>{Format(announcement.DeployedOn)}</strong>.")
            .AppendParagraph($"<strong>Project:</strong> {Encode(announcement.ProjectName)}")
            .AppendParagraph($"<strong>Version:</strong> {Encode(announcement.Version)}")
            .AppendParagraph($"<strong>Lead developer:</strong> {Encode(announcement.LeadDeveloper)}");

        if (!string.IsNullOrWhiteSpace(announcement.ReleaseNotes))
            builder.AppendParagraph($"<strong>Release notes:</strong><br/>{ToHtml(announcement.ReleaseNotes)}");

        return (subject, builder.AppendSignature(Signature, SignatureApp).GenerateContent());
    }

    public (string Subject, string BodyHtml) Compose(RollbackAnnouncement announcement)
    {
        var subject = $"[Rolled back] {announcement.ProjectName} {announcement.Version} - {Format(announcement.RolledBackOn)}";

        var builder = new PodEmailBuilder()
            .AppendTitle($"{announcement.ProjectName} {announcement.Version} has been rolled back")
            .AppendParagraph($"A production release has been reverted at <strong>{Format(announcement.RolledBackOn)}</strong>.")
            .AppendParagraph($"<strong>Project:</strong> {Encode(announcement.ProjectName)}")
            .AppendParagraph($"<strong>Version rolled back:</strong> {Encode(announcement.Version)}, deployed {Format(announcement.OriginalDeployedOn)}")
            .AppendParagraph($"<strong>Lead developer:</strong> {Encode(announcement.LeadDeveloper)}");

        if (!string.IsNullOrWhiteSpace(announcement.RollbackReason))
            builder.AppendParagraph($"<strong>Reason for rollback:</strong><br/>{ToHtml(announcement.RollbackReason)}");

        return (subject, builder.AppendSignature(Signature, SignatureApp).GenerateContent());
    }

    private static string Format(DateTime value) => value.ToString("dd/MM/yyyy HH:mm");

    /// Normalises line endings, THEN encodes, THEN turns \n into <br/> - in that order, so a typed
    /// "<br/>" is escaped rather than honoured.
    private static string ToHtml(string value) => Encode(value)?.Replace("\n", "<br/>");

    private static string Encode(string value) =>
        System.Net.WebUtility.HtmlEncode(value?.Replace("\r\n", "\n").Replace("\r", "\n"));
}
